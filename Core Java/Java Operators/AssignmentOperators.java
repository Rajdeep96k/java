class AssignmentOperators 
{
	public static void main(String[] args) 
	{
		int num=10;
		int b=2;
		
		num+=b;  //num=num+b
		System.out.println(num);

        num-=b; //num=num-b
		System.out.println(num);

        num*=b; //num=num*b
		System.out.println(num);

        num/=b; //num=num/b
		System.out.println(num);

        num%=b; //num=nu%b
		System.out.println(num);

	}
}